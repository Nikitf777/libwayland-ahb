#!/system/bin/env python3
"""Generate direct-call forwarders for the native Vulkan loader.

vkcube resolves Vulkan entry points through vkGetInstanceProcAddr, but
libraries such as wlroots link directly against libvulkan.so.1.  A replacement
libvulkan must therefore export every entry point those libraries reference,
not just the ones the shim wraps.

Each generated symbol is a tiny tail-call stub that jumps through a slot filled
by the constructor in vulkan_forwarders.c.  This preserves all argument
registers and avoids needing a prototype for every Vulkan command.

Usage:
    scripts/generate-vulkan-forwarders.py [/system/lib64/libvulkan.so]
"""

from pathlib import Path
import subprocess
import sys

# Entry points implemented by the shim itself.  They must not be overridden by
# a native forwarder.
SHIM_EXPORTS = {
    "vkCreateInstance",
    "vkEnumerateInstanceExtensionProperties",
    "vkEnumerateInstanceLayerProperties",
    "vkEnumerateInstanceVersion",
    "vkGetInstanceProcAddr",
    "vkGetDeviceProcAddr",
    "vkCreateWaylandSurfaceKHR",
    "vkDestroySurfaceKHR",
    "vkGetPhysicalDeviceWaylandPresentationSupportKHR",
    "vkGetPhysicalDeviceSurfaceCapabilitiesKHR",
    "vkCreateSwapchainKHR",
    "vkDestroySwapchainKHR",
}


def main() -> int:
    loader = sys.argv[1] if len(sys.argv) > 1 else "/system/lib64/libvulkan.so"
    output = subprocess.check_output(
        ["nm", "-D", "--defined-only", loader], text=True
    )

    symbols = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) < 3:
            continue
        kind, name = fields[-2], fields[-1]
        if kind in ("T", "t", "W", "w") and name.startswith("vk"):
            symbols.add(name)

    symbols.difference_update(SHIM_EXPORTS)
    if not symbols:
        print(f"no Vulkan symbols found in {loader}", file=sys.stderr)
        return 1

    root = Path(__file__).resolve().parent.parent
    src = root / "src"
    names = sorted(symbols)

    asm = [
        "/* Generated by scripts/generate-vulkan-forwarders.py. */",
        "/* Do not edit; re-run the generator after changing the native loader. */",
        "",
        "#if defined(__aarch64__)",
        "",
        "#define VK_FORWARD(name) \\",
        "    .text; \\",
        "    .p2align 2; \\",
        "    .globl name; \\",
        "    .type name, %function; \\",
        "name: \\",
        "    .inst 0xd503245f; /* bti c */ \\",
        "    adrp x16, vkwl_slot_##name; \\",
        "    ldr x16, [x16, #:lo12:vkwl_slot_##name]; \\",
        "    br x16; \\",
        "    .size name, .-name; \\",
        "    .data; \\",
        "    .p2align 3; \\",
        "    .globl vkwl_slot_##name; \\",
        "    .hidden vkwl_slot_##name; \\",
        "vkwl_slot_##name: \\",
        "    .quad 0",
        "",
        "#elif defined(__x86_64__)",
        "",
        "#define VK_FORWARD(name) \\",
        "    .text; \\",
        "    .p2align 4; \\",
        "    .globl name; \\",
        "    .type name, %function; \\",
        "name: \\",
        "    jmp *vkwl_slot_##name(%rip); \\",
        "    .size name, .-name; \\",
        "    .data; \\",
        "    .p2align 3; \\",
        "    .globl vkwl_slot_##name; \\",
        "    .hidden vkwl_slot_##name; \\",
        "vkwl_slot_##name: \\",
        "    .quad 0",
        "",
        "#else",
        '#error "vulkan forwarders need aarch64 or x86_64"',
        "#endif",
        "",
    ]
    asm.extend(f"VK_FORWARD({name})" for name in names)
    asm.extend(["", '.section .note.GNU-stack,"",@progbits', ""])
    (src / "vulkan_forwarders.S").write_text("\n".join(asm))

    c = [
        "/* Generated by scripts/generate-vulkan-forwarders.py. */",
        "/* Do not edit; re-run the generator after changing the native loader. */",
        "",
        "#include <stddef.h>",
        "",
        "struct vkwl_forward {",
        "    const char *name;",
        "    void **slot;",
        "};",
        "",
    ]
    c.extend(f"extern void *vkwl_slot_{name};" for name in names)
    c.extend(["", "static const struct vkwl_forward vkwl_forwards[] = {"])
    c.extend(f'    {{ "{name}", &vkwl_slot_{name} }},' for name in names)
    c.extend(
        [
            "};",
            "",
            "extern void *vkwl_lookup_native(const char *name);",
            "",
            "__attribute__((constructor)) static void vkwl_bind_forwarders(void)",
            "{",
            "    for (size_t i = 0; i < sizeof(vkwl_forwards) / sizeof(vkwl_forwards[0]); i++) {",
            "        *vkwl_forwards[i].slot = vkwl_lookup_native(vkwl_forwards[i].name);",
            "    }",
            "}",
            "",
        ]
    )
    (src / "vulkan_forwarders.c").write_text("\n".join(c))

    print(f"generated {len(names)} Vulkan forwarders from {loader}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
