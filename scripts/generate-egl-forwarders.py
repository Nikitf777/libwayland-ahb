#!/system/bin/env python3
"""Generate direct-call forwarders for the platform EGL library.

Directly-linked Wayland clients (Weston, wlroots, GTK, ...) resolve EGL
symbols at load time.  The shim therefore has to export every entry point the
platform libEGL exports, except the ones it implements itself.

Each generated symbol is a tiny tail-call stub that jumps through a slot filled
by the constructor in egl_forwarders.c.  This preserves all argument registers
and avoids needing a prototype for every EGL command.

Usage:
    scripts/generate-egl-forwarders.py [/system/lib64/libEGL.so]
"""

from pathlib import Path
import subprocess
import sys

# Entry points implemented by the shim itself.  They must not be overridden by
# a native forwarder.
SHIM_EXPORTS = {
    "eglGetDisplay",
    "eglGetPlatformDisplay",
    "eglGetPlatformDisplayEXT",
    "eglCreateWindowSurface",
    "eglCreatePlatformWindowSurface",
    "eglCreatePlatformWindowSurfaceEXT",
    "eglQueryString",
    "eglGetProcAddress",
}


def defined_functions(library: str, prefix: str | None = None) -> set[str]:
    output = subprocess.check_output(
        ["nm", "-D", "--defined-only", library], text=True
    )
    symbols = set()
    for line in output.splitlines():
        fields = line.split()
        if len(fields) < 3:
            continue
        kind, name = fields[-2], fields[-1]
        if kind in ("T", "t", "W", "w") and (prefix is None or name.startswith(prefix)):
            symbols.add(name)
    return symbols


def undefined_symbols(library: str) -> set[str]:
    output = subprocess.check_output(
        ["nm", "-D", "--undefined-only", library], text=True
    )
    return {line.split()[-1] for line in output.splitlines() if len(line.split()) >= 2}


def main() -> int:
    loader = sys.argv[1] if len(sys.argv) > 1 else "/system/lib64/libEGL.so"
    gles = sys.argv[2] if len(sys.argv) > 2 else "/system/lib64/libGLESv2.so"

    symbols = defined_functions(loader, "egl")

    # The platform GLES loader links against Android-internal libEGL symbols
    # (for example _ZN7android18egl_get_connectionEv).  Our libEGL shim replaces
    # the platform library for that loader too, so forward every symbol the
    # GLES loader needs that libEGL provides.
    try:
        symbols.update(defined_functions(loader) & undefined_symbols(gles))
    except (FileNotFoundError, subprocess.CalledProcessError):
        # Keep the public EGL set when the GLES library is unavailable.
        pass

    symbols.difference_update(SHIM_EXPORTS)
    if not symbols:
        print(f"no EGL symbols found in {loader}", file=sys.stderr)
        return 1

    root = Path(__file__).resolve().parent.parent
    src = root / "src"
    names = sorted(symbols)

    asm = [
        "/* Generated by scripts/generate-egl-forwarders.py. */",
        "/* Do not edit; re-run the generator after changing the platform EGL. */",
        "",
        "#if defined(__aarch64__)",
        "",
        "#define VKWL_EGL_FORWARD(name) \\",
        "    .text; \\",
        "    .p2align 2; \\",
        "    .globl name; \\",
        "    .type name, %function; \\",
        "name: \\",
        "    .inst 0xd503245f; /* bti c */ \\",
        "    adrp x16, vkwl_egl_slot_##name; \\",
        "    ldr x16, [x16, #:lo12:vkwl_egl_slot_##name]; \\",
        "    br x16; \\",
        "    .size name, .-name; \\",
        "    .data; \\",
        "    .p2align 3; \\",
        "    .globl vkwl_egl_slot_##name; \\",
        "    .hidden vkwl_egl_slot_##name; \\",
        "vkwl_egl_slot_##name: \\",
        "    .quad 0",
        "",
        "#elif defined(__x86_64__)",
        "",
        "#define VKWL_EGL_FORWARD(name) \\",
        "    .text; \\",
        "    .p2align 4; \\",
        "    .globl name; \\",
        "    .type name, %function; \\",
        "name: \\",
        "    jmp *vkwl_egl_slot_##name(%rip); \\",
        "    .size name, .-name; \\",
        "    .data; \\",
        "    .p2align 3; \\",
        "    .globl vkwl_egl_slot_##name; \\",
        "    .hidden vkwl_egl_slot_##name; \\",
        "vkwl_egl_slot_##name: \\",
        "    .quad 0",
        "",
        "#else",
        '#error "EGL forwarders need aarch64 or x86_64"',
        "#endif",
        "",
    ]
    asm.extend(f"VKWL_EGL_FORWARD({name})" for name in names)
    asm.extend(["", '.section .note.GNU-stack,"",@progbits', ""])
    (src / "egl_forwarders.S").write_text("\n".join(asm))

    c = [
        "/* Generated by scripts/generate-egl-forwarders.py. */",
        "/* Do not edit; re-run the generator after changing the platform EGL. */",
        "",
        "#include <stddef.h>",
        "",
        "struct vkwl_egl_forward {",
        "    const char *name;",
        "    void **slot;",
        "};",
        "",
    ]
    c.extend(f"extern void *vkwl_egl_slot_{name};" for name in names)
    c.extend(["", "static const struct vkwl_egl_forward vkwl_egl_forwards[] = {"])
    c.extend(f'    {{ "{name}", &vkwl_egl_slot_{name} }},' for name in names)
    c.extend(
        [
            "};",
            "",
            "extern void *vkwl_lookup_egl_native(const char *name);",
            "",
            "__attribute__((constructor)) static void vkwl_egl_bind_forwarders(void)",
            "{",
            "    for (size_t i = 0; i < sizeof(vkwl_egl_forwards) / sizeof(vkwl_egl_forwards[0]); i++) {",
            "        *vkwl_egl_forwards[i].slot = vkwl_lookup_egl_native(vkwl_egl_forwards[i].name);",
            "    }",
            "}",
            "",
        ]
    )
    (src / "egl_forwarders.c").write_text("\n".join(c))

    print(f"generated {len(names)} EGL forwarders from {loader}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
